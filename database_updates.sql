-- Discounts
create table public.discounts (
  id text not null,
  name text null,
  type text null,
  value numeric null,
  active boolean null,
  trigger_type text null default 'MANUAL'::text,
  trigger_value text null,
  start_date text null,
  end_date text null,
  is_permanent boolean null default true,
  constraint discounts_pkey primary key (id)
