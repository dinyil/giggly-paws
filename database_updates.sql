-- Logs
create table public.logs (
  id text not null,
  action text null,
  details text null,
  timestamp text null,
  "userId" text null,
  "referenceId" text null,
  constraint logs_pkey primary key (id)
) TABLESPACE pg_default;

-- Messages
create table public.messages (
  id text not null,
  client_id text not null,
  direction text not null,
  channel text not null,
  content text not null,
  timestamp timestamp with time zone null default now(),
  status text null default 'SENT'::text,
  read boolean null default false,
  constraint messages_pkey primary key (id),
  constraint messages_client_id_fkey foreign KEY (client_id) references clients (id) on delete CASCADE,
  constraint messages_channel_check check (
    (channel = any (array['SMS'::text, 'EMAIL'::text]))
  ),
  constraint messages_direction_check check (
    (
      direction = any (array['INBOUND'::text, 'OUTBOUND'::text])
    )
  )
) TABLESPACE pg_default;

-- Product Categories
create table public.product_categories (
  id bigint generated by default as identity not null,
